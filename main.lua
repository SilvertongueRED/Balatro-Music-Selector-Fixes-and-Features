if not cardsauce_detected then -- For now, the mod is designed to not load if Cardsauce is enabled to prevent conflicts. I may try working around this in the future, possibly by trying to inject extra tracks if detected, or try to override its own selector (at worst).
 local setting_tabRef = G.UIDEF.settings_tab --[[ The letter "G" stand for "Game", and it's a Balatro native global function.
 "UIDEF" is the table containing the definitions to add UI elements. In this case, it's calling a function to define a tab for the settings menu ("settings_tab") and the value it returns will be used as a variable.]]
 function G.UIDEF.settings_tab(tab) -- Runs the "G.UIDEF.settings_tab" functions and assigns it "tab" as an argument.
  local setting_tab
  if tab == 'Audio' then
   -- Lost Edition (and any other mod that uses the shared 'change_music' callback) draws its own
   -- soundtrack cycler. Swap it for an empty row while the tab is being built so only OURS is shown.
   local real_cycle = create_option_cycle
   create_option_cycle = function(args)
    if type(args) == 'table' and args.opt_callback == 'change_music' then
     return { n = G.UIT.R, config = { align = 'cm' }, nodes = {} }
    end
    return real_cycle(args)
   end
   local ok, res = pcall(setting_tabRef, tab)
   create_option_cycle = real_cycle
   if not ok then error(res) end
   setting_tab = res
  else
   setting_tab = setting_tabRef(tab) -- The variable will return the result of "setting_tabRef" with the given argument as a value.
  end
   if tab == 'Audio' then -- This makes the game render the selector in the Audio tab.
    local options_table = {}
    for i, val in ipairs(music_vals_list) do
     options_table[i] = pack_display_names[val] or val --[[Broken down:
     options_table[i] = gives itself the value returned to "i" to be considered as that value, in this case the music pack name found inside "music_vals_list".
     pack_display_names[val] = if "val" corresponds to a variable inside the "pack_display_names" table, it'll return its value (in this case, the soundtrack name and artist).
     val = acts as a fallback should any of the given values not exist.
     ]]
    end
    local musicSelector = {
    n=G.UIT.R, -- Steamodded function to render a Row node (arranges its child nodes horizontally).
    config = { -- Defines the appearance of the selector, similar to how CSS works.
    align = 'cm', -- "align = 'cm'" aligns the node both on the vertical and horizontal axis.
    r = 0 -- "r = 0" sets the roundness of the corners to 0. See https://github.com/Steamodded/smods/wiki/UI-Guide to learn more.
    },  
    nodes= {
     create_option_cycle({
     w = 8, -- Specifies the width of the selector.
     scale = 1, -- Defines the scale of the entire selector (text and graphics).
     label = localize('b_muselector'),
     options = options_table, -- Shows the track name and artist returned by the "options_table" variable.
     opt_callback = 'change_music',
     current_option = ((music_nums)[G.SETTINGS.music_selection] or 1) })
    }}
    setting_tab.nodes[#setting_tab.nodes + 1] = musicSelector
  end
  return setting_tab
 end

 -- Sets the current music in balatro's settings to one of the given args.
 -- It uses OUR list directly (not the shared G.ARGS.music_vals, which other mods fill in a different
 -- order) so the option you pick is always the soundtrack that plays.
 local function musel_change_music(args)
  local pick = music_vals_list[args.to_key]
  if not pick then return end
  G.SETTINGS.QUEUED_CHANGE = G.SETTINGS.QUEUED_CHANGE or {}
  G.SETTINGS.QUEUED_CHANGE.music_change = pick
  G.SETTINGS.music_selection = pick
  G.ARGS.music_vals = music_vals_list
  if G.save_settings then G:save_settings() end
 end
 G.FUNCS.change_music = musel_change_music
 -- Other mods (Lost Edition) define the same callback name; make sure ours is the one that is live
 -- every time the settings menu is opened.
 local settings_tab_inner = G.UIDEF.settings_tab
 function G.UIDEF.settings_tab(tab)
  G.FUNCS.change_music = musel_change_music
  local built = settings_tab_inner(tab)
  G.FUNCS.change_music = musel_change_music -- again AFTER, in case another mod's hook replaced it while the tab was built
  return built
 end
