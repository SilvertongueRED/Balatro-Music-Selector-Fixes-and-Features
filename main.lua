-- TRACK GROUPS (speed fix) --------------------------------------------------------------------------
-- The game starts EVERY registered music track at once (all soundtracks of all mods = 80+ tracks), but the audio
-- system can only play 64 sounds at a time. That overflow is what made soundtracks slow to start or silent until
-- you switched menu tabs and picked again. We tell the audio thread which tracks belong together (one soundtrack),
-- and lovely/sound_limit.toml makes it start only those. MUSEL_PACK_OF[track_key] = { [track_key] = true, ... }
MUSEL_PACK_OF = MUSEL_PACK_OF or {}
local musel_group_cache = {}
local function musel_stem(key) return (string.gsub(key, '%d+$', '')) end
function MUSEL_GET_GROUP(desired)
 if not desired or desired == '' then return {} end
 local cached = musel_group_cache[desired]
 if cached then return cached end
 local group
 if MUSEL_PACK_OF[desired] then
  group = MUSEL_PACK_OF[desired] -- one of our soundtracks: its whole set of tracks
 else
  group = { [desired] = true }
  if string.find(desired, '^music%d+$') then
   for i = 1, 5 do group['music' .. i] = true end -- the vanilla soundtrack
  else
   local stem = musel_stem(desired) -- other mods: tracks named alike (xyz_music1..5) belong together
   for _, key in ipairs(SMODS.Sound.obj_buffer) do
    if type(key) == 'string' and string.find(key, 'music') and musel_stem(key) == stem then group[key] = true end
   end
  end
 end
 musel_group_cache[desired] = group
 return group
end

local music_nums = { balatro = 1 }
local music_vals_list = { 'balatro' }
local next_music_num_id = { 2 }
local pack_display_names = { balatro = "Balatro OST - LouisF", }

--[[ Anything wrapped inside curly brackets is called a "table". An entry formatted like "x = y," makes said table a "dictionary".

Lua allows to call these tables whenever you may need its contents.

In this case, Steamodded allows to make tables inside the code with localization keys to have a simple way to add different languages to small tidbits of text. A table is considered an "object" by Lua.]]

for _, mpacks in ipairs(mpack_files) do --[[Broken down, this statement reads:
for = begins a loop that will repeat any action past the whole statement for as long as it possibly can.
_, = receives the first result of a function, however using "_," makes lua ignore whatever value it'll receive from a function. In concrete terms, it behaves like a trashcan.
mpack = receives the second result of a function.
in = instructs the loop to use the values given by the next function.
ipairs(mpack_files) = goes through every entry in the defined table (mpack_files) up to the next interruption.
do = closes the loop statement. Everything beyond this, up to "end", will run in loop]]
 local mpack_path = "/assets/sounds/" .. mpacks .. "/mpack_" .. mpacks .. ".lua" --[[This variable is used to return the lua file path for the music pack as a value.
 
 ".." in lua is a concatenation: any value the named variable returns will be added to the string as text (in this context, "mpacks" will add the entries from the "mpack_files" table.
 
 ".." must be positioned to the side(s) where the variable is going to concatenate at.]]
 local buffer_before = #SMODS.Sound.obj_buffer -- remember how many sounds exist, so we can tell which ones THIS soundtrack adds
 local setupit, err = assert(SMODS.load_file(mpack_path))()--[[Broken down:
 setupit, = receives the first result of a function.
 err = receives the second result of a function.
 assert(SMODS.load_file(mpack_path))() = "assert" is a function that checks if the first argument is true (in this case, the result of the "load_file" function located inside the "SMODS" table, which will try to load a file from "mpack_path") and returns it, otherwise it'll return an error message (optional) as second result.]]
 if not setupit then -- If the file doesn't exist or is invalid (so, "setupit" didn't return any value), it'll do the following.
  print("Loading error " .. mpack_path .. ":" .. err)
 else -- If the previous condition dindn't occur, it'll do the following.
  setupit(music_nums, music_vals_list, pack_display_names, next_music_num_id) -- Each music pack has a lua file with its own function that will return its own values to be assigned to the respective variables.
  -- Remember which tracks belong to this soundtrack (used by the "only play one soundtrack at a time" fix below).
  local members = {}
  for i = buffer_before + 1, #SMODS.Sound.obj_buffer do
   local track_key = SMODS.Sound.obj_buffer[i]
   if type(track_key) == 'string' and string.find(track_key, 'music') then members[track_key] = true end
  end
  for track_key in pairs(members) do MUSEL_PACK_OF[track_key] = members end
 end -- This ends "if not".
end -- This ends the loop.

-- GRAB BAG OST (hooked in) ---------------------------------------------------------------------
-- Grab Bag ships its own soundtrack (5 tracks, made by ViperDemon). With Grab Bag's "Custom Music" checkbox on it plays
-- them no matter which soundtrack is picked here, which overrode every soundtrack of this mod.
-- Instead of copying its audio, we list it as an option and only let its tracks play while it is the selected one.
--   * Custom Music ON in Grab Bag: Grab Bag registered the tracks itself, so we wrap its rules (silent unless selected).
--   * Custom Music OFF in Grab Bag: Grab Bag registers nothing (so the old check found no tracks and the option never
--     showed up). We register the same five files straight from Grab Bag's folder, with Grab Bag's own rules, and only
--     while "Grab Bag OST" is selected. Nothing is copied.
-- Either way the option only appears when Grab Bag is installed and enabled.
if not cardsauce_detected then
 local grabbag_tracks = {}
 local grabbag_mod = SMODS.find_mod and SMODS.find_mod('GrabBag')[1]
 if grabbag_mod then
  for _, track_key in ipairs(SMODS.Sound.obj_buffer) do
   local snd = SMODS.Sounds[track_key]
   if type(track_key) == 'string' and string.find(track_key, 'music') and snd and snd.mod and snd.mod.id == 'GrabBag'
    and type(snd.select_music_track) == 'function' and not snd.musel_gated then
    local original_select = snd.select_music_track
    snd.select_music_track = function(self, ...)
     if G.SETTINGS.music_selection ~= 'grabbag' then return false end -- not picked here: stay silent
     return original_select(self, ...) -- picked: Grab Bag's own rules (menu, packs, shop, boss)
    end
    snd.musel_gated = true
    grabbag_tracks[#grabbag_tracks + 1] = track_key
   end
  end

  if #grabbag_tracks == 0 and grabbag_mod.path then -- Custom Music is off in Grab Bag: register its files ourselves
   local gb_path = grabbag_mod.path
   local function gb_file_exists(name)
    local f = io.open(gb_path .. 'assets/sounds/' .. name, 'rb')
    if f then f:close() return true end
    return false
   end
   local gb_rules = {
    [1] = function() return 10 end,
    [2] = function() return (G.booster_pack_sparkles and not G.booster_pack_sparkles.REMOVED) and 11 or false end,
    [3] = function() return (G.booster_pack_meteors and not G.booster_pack_meteors.REMOVED) and 11 or false end,
    [4] = function() return (G.shop and not G.shop.REMOVED) and 11 or false end,
    [5] = function() return (G.GAME and G.GAME.blind and G.GAME.blind.boss) and 11 or false end,
   }
   local before = #SMODS.Sound.obj_buffer
   for i = 1, 5 do
    local file = 'gb_music' .. i .. '.ogg'
    if gb_file_exists(file) then
     SMODS.Sound({
      vol = 0.35,
      pitch = 1,
      key = 'gb_music' .. i,
      path = file,
      path_mod = grabbag_mod, -- read the audio from Grab Bag's own assets/sounds folder
      select_music_track = function()
       if G.SETTINGS.music_selection ~= 'grabbag' then return false end
       return gb_rules[i]()
      end,
     })
    end
   end
   local members = {}
   for i = before + 1, #SMODS.Sound.obj_buffer do
    local track_key = SMODS.Sound.obj_buffer[i]
    if type(track_key) == 'string' and string.find(track_key, 'music') then
     members[track_key] = true
     grabbag_tracks[#grabbag_tracks + 1] = track_key
    end
   end
   for track_key in pairs(members) do MUSEL_PACK_OF[track_key] = members end -- the 64-voice fix groups them like our packs
  end
 end
 if #grabbag_tracks > 0 then
  music_nums['grabbag'] = next_music_num_id[1]
  table.insert(music_vals_list, 'grabbag')
  pack_display_names['grabbag'] = "Grab Bag OST - ViperDemon"
  next_music_num_id[1] = next_music_num_id[1] + 1
 end
end

